#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = ["pyyaml"]
# ///
"""Adapters: common rulebook personas -> per-harness surfaces.

The common layer (personas/*.yaml) is the single truth — harness-neutral,
model-agnostic. Each adapter implements the ADAPTER INTERFACE and compiles
the rulebook into its harness's native lifecycle mechanism. Generated files
carry a header pointing back at the source; never hand-edit them.

ADAPTER INTERFACE (mirrors Agents/personas/adapters/build.py)
    @adapter("harness") -> list[GeneratedFile(write_root, relpath, content, exec)]
    The adapter's job is ONLY translation: map the common schema onto the
    harness's native artifact and lifecycle. New harness = one function +
    registration, documented in ../README.md. Nothing else changes.

Lifecycle parity (full table in ../README.md):
    claude — SessionStart/UserPromptSubmit/SubagentStart hooks cat the bodies
             (full on session start, --line per prompt), payload <10KB hard cap
    pi     — a before_agent_start extension appends the rulebook to the system
             prompt every run (no size cliff measured; --extension loads it)
    dsh    — not implemented (cordis persona patch format not yet studied)

    build.py [--check] [harness ...]    # --check = regenerate + diff, exit 1 on drift
"""

import sys
from dataclasses import dataclass, field
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
PERSONAS = REPO / "personas"
TEMPLATES = Path(__file__).resolve().parent / "templates"
REQUIRED = ("name", "kind", "order", "description", "method")

GENERATED_NOTE = ("<!-- generated by adapters/build.py from personas/{src}.yaml "
                  "— edit the source, never this file -->")


@dataclass
class GeneratedFile:
    write_root: str
    relpath: str
    content: str
    exec_: bool = False


_ADAPTERS = {}


def adapter(name):
    def wrap(fn):
        _ADAPTERS[name] = fn
        return fn
    return wrap


def load_personas() -> list[dict]:
    out = []
    for f in sorted(PERSONAS.glob("*.yaml")):
        p = yaml.safe_load(f.read_text())
        missing = [k for k in REQUIRED if k not in p or not str(p[k]).strip()]
        if missing:
            sys.exit(f"{f.name}: missing fields {missing}")
        out.append(p)
    if not out:
        sys.exit(f"no personas found in {PERSONAS}")
    out.sort(key=lambda p: p["order"])  # glob order == axis order (load-bearing)
    return out


# ── claude adapter ───────────────────────────────────────────────────────

@adapter("claude")
def adapt_claude(personas: list[dict]) -> list[GeneratedFile]:
    """A complete claude plugin: SessionStart cats full bodies, every
    UserPromptSubmit re-injects the one --line, SubagentStart cats bodies."""
    root = REPO / "surfaces" / "claude-plugin"
    out = []
    for p in personas:
        stem = p["name"].replace("on-point-ste-", "")
        rel = f"{stem}.md"
        body = p["method"].rstrip() + "\n"
        out.append(GeneratedFile(str(root), f"personas/{rel}", body))
    out.append(GeneratedFile(str(root), "hooks/inject.sh",
                             (TEMPLATES / "claude/inject.sh").read_text(), exec_=True))
    out.append(GeneratedFile(str(root), "hooks/hooks.json",
                             (TEMPLATES / "claude/hooks.json").read_text()))
    out.append(GeneratedFile(str(root), ".claude-plugin/plugin.json",
                             (TEMPLATES / "claude/plugin.json").read_text()))
    style = (TEMPLATES / "claude/output-style.md").read_text()
    out.append(GeneratedFile(str(root), "output-styles/on-point.md",
                             style + f"\n{GENERATED_NOTE.format(src='(all personas)')}\n"))
    return out


# ── pi adapter ───────────────────────────────────────────────────────────

EXT_TMPL = """\
/**
 * On Point (ASD-STE100) — generated by adapters/build.py from personas/*.yaml.
 * Edit the source, never this file.
 *
 * Lifecycle parity with the claude plugin: the claude form injects via
 * SessionStart/UserPromptSubmit hooks; pi runs one agent loop, so
 * before_agent_start appends the rulebook to the system prompt every run.
 * Load: pi --extension <repo>/surfaces/pi/extension/on-point-ste.ts
 */
import type {{ ExtensionAPI }} from "@earendil-works/pi-coding-agent";

const RULEBOOK = {rulebook};

export default function (pi: ExtensionAPI) {{
\tlet active = true;
\t// /on-point-ste off|on — the rulebook is identity, deployment decides the model
\tpi.registerCommand("on-point-ste", {{
\t\tdescription: "Toggle the On Point (STE100) rulebook",
\t\thandler: async (arg, ctx) => {{
\t\t\tactive = arg !== "off";
\t\t\tctx.ui.notify(`On Point (STE100) ${{active ? "active" : "off"}}`, "info");
\t\t}},
\t}});
\tpi.on("before_agent_start", async (event) => {{
\t\tif (!active) return;
\t\treturn {{ systemPrompt: event.systemPrompt + "\\n\\n" + RULEBOOK }};
\t}});
}}
"""


@adapter("pi")
def adapt_pi(personas: list[dict]) -> list[GeneratedFile]:
    """Two pi surfaces: (1) the bare rulebook body — the --append-system-prompt
    channel the A/B harness proved; (2) an extension that auto-injects it on
    every run, the lifecycle twin of the claude hooks."""
    root = REPO / "surfaces" / "pi"
    bodies = "\n".join(p["method"].rstrip() for p in personas) + "\n"
    lit = bodies.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")
    ext = EXT_TMPL.format(rulebook="`\n" + lit + "`")
    ext = ext.replace("by adapters/build.py from personas/*.yaml",
                      "by adapters/build.py from personas/*.yaml")
    return [
        GeneratedFile(str(root), "bodies/on-point-ste.md", bodies),
        GeneratedFile(str(root), "extension/on-point-ste.ts", ext),
    ]


# ── build / check ────────────────────────────────────────────────────────

def build(harnesses: list[str], check: bool) -> int:
    personas = load_personas()
    unknown = [h for h in harnesses if h not in _ADAPTERS]
    if unknown:
        sys.exit(f"no adapter for: {', '.join(unknown)} (have: {', '.join(_ADAPTERS)})")
    drift, wrote, total_bytes = [], 0, 0
    for h in harnesses:
        for gf in _ADAPTERS[h](personas):
            dest = Path(gf.write_root) / gf.relpath
            if check:
                if not dest.is_file() or dest.read_text() != gf.content:
                    drift.append(str(dest))
                continue
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(gf.content)
            if gf.exec_:
                dest.chmod(0o755)
            wrote += 1
            total_bytes += len(gf.content)
    if check:
        if drift:
            print("STALE/MISSING:\n  " + "\n  ".join(drift))
            return 1
        print(f"CHECK OK: {len(personas)} personas x {len(harnesses)} harness(es), no drift")
        return 0
    print(f"wrote {wrote} files ({total_bytes}B) from {len(personas)} personas")
    return 0


if __name__ == "__main__":
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("harnesses", nargs="*", choices=["claude", "pi", "dsh"])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    sys.exit(build(args.harnesses or ["claude", "pi"], args.check))
